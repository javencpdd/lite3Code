#!/usr/bin/env bash
# ============================================================
# 关闭（手工模式：只停进程，不影响 systemd 的 enable 状态）
# ============================================================
# 用法：./stop.sh [all|yolo|rosbridge]
#   默认 all —— 把本部署拉起的进程全部停干净，不留残留。
# ============================================================
set -euo pipefail

cd "$(dirname "$(readlink -f "$0")")"

exec ./lite3-publish-ctl.sh stop "${1:-all}"
